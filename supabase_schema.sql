-- สร้างนโยบายอ่าน/เขียนสาธารณะสำหรับแอปรองรับ Anon Key
DO $$
DECLARE
    tbl text;
    tables text[] := ARRAY[
        'system_settings', 'warehouses', 'users', 'vendors', 'customers',
        'products', 'purchase_orders', 'goods_receipts', 'purchase_payments',
        'sales_orders', 'sales_receipts', 'requisitions', 'shipments', 'login_history'
    ];
BEGIN
    FOREACH tbl IN ARRAY tables LOOP
        EXECUTE format('DROP POLICY IF EXISTS "Public read access on %I" ON public.%I', tbl, tbl);
        EXECUTE format('CREATE POLICY "Public read access on %I" ON public.%I FOR SELECT USING (true)', tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS "Public insert access on %I" ON public.%I', tbl, tbl);
        EXECUTE format('CREATE POLICY "Public insert access on %I" ON public.%I FOR INSERT WITH CHECK (true)', tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS "Public update access on %I" ON public.%I', tbl, tbl);
        EXECUTE format('CREATE POLICY "Public update access on %I" ON public.%I FOR UPDATE USING (true) WITH CHECK (true)', tbl, tbl);
        
        EXECUTE format('DROP POLICY IF EXISTS "Public delete access on %I" ON public.%I', tbl, tbl);
        EXECUTE format('CREATE POLICY "Public delete access on %I" ON public.%I FOR DELETE USING (true)', tbl, tbl);
    END LOOP;
END $$;

