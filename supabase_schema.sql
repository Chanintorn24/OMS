-- ==============================================================================
-- TABLE 1: system_settings (ข้อมูลบริษัทและการตั้งค่าระบบ)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.system_settings (
    id TEXT PRIMARY KEY DEFAULT 'default',
    company_name TEXT NOT NULL DEFAULT 'บริษัท โอเอ็มเอส โซลูชั่น จำกัด',
    company_address TEXT DEFAULT '123/45 หมู่ 1 ถ.สุขุมวิท ต.คลองเตย อ.คลองเตย จ.กรุงเทพมหานคร 10110',
    tax_id TEXT DEFAULT '0105555555555',
    banks JSONB DEFAULT '[{"bank": "กสิกรไทย", "branch": "สุขุมวิท", "account_name": "บจก. โอเอ็มเอส", "account_no": "0123456789"}]'::jsonb,
    security_settings JSONB DEFAULT '{"maxFailedBeforeDelay": 5, "delaySeconds": 30, "maxFailedBeforeLock": 10}'::jsonb,
    updated_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ==============================================================================
-- TABLE 2: warehouses (คลังสินค้า)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.warehouses (
    id TEXT PRIMARY KEY,
    name TEXT NOT NULL,
    address JSONB DEFAULT '{}'::jsonb,
    contact TEXT,
    phone TEXT,
    type TEXT DEFAULT 'sub', -- 'main', 'sub', 'sales'
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ==============================================================================
-- TABLE 3: users (ผู้ใช้งานระบบ)
-- ==============================================================================
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password_hash TEXT DEFAULT '123',
    fullname TEXT NOT NULL,
    nickname TEXT,
    phone TEXT,
    email TEXT,
    role TEXT NOT NULL DEFAULT 'sales', -- admin, purchasing, warehouse, sales, accounting, management
    area TEXT DEFAULT 'HQ',
    warehouse_id TEXT REFERENCES public.warehouses(id) ON DELETE SET NULL,
    shipping_address TEXT DEFAULT '-',
    failed_attempts INTEGER DEFAULT 0,
    locked_until TIMESTAMPTZ,
    created_at TIMESTAMPTZ DEFAULT TIMEZONE('utc'::text, NOW())
);

-- ==============================================================================
-- TABLE 4: vendors (ผู้จัดจำหน่าย / ซัพพลายเออร์)
