-- GRANT PERMISSIONS TO ANON AND AUTHENTICATED ROLES
-- แก้ปัญหา "permission denied for table ..." สำหรับ Supabase REST API
-- ==============================================================================
GRANT USAGE ON SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL TABLES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL SEQUENCES IN SCHEMA public TO anon, authenticated, service_role;
GRANT ALL ON ALL ROUTINES IN SCHEMA public TO anon, authenticated, service_role;

ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON TABLES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON SEQUENCES TO anon, authenticated, service_role;
ALTER DEFAULT PRIVILEGES IN SCHEMA public GRANT ALL ON ROUTINES TO anon, authenticated, service_role;

-- ==============================================================================
-- SUPABASE STORAGE BUCKET: oms-storage
-- สำหรับเก็บสลิปการโอนเงิน (slips/), ใบกำกับภาษี (invoices/), รูปสินค้า (products/)
-- ==============================================================================
INSERT INTO storage.buckets (id, name, public)
VALUES ('oms-storage', 'oms-storage', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- นโยบาย Storage ให้ทุกคนสามารถดูรูปได้ (Public Read)
DROP POLICY IF EXISTS "Public Storage Read" ON storage.objects;
CREATE POLICY "Public Storage Read" ON storage.objects
FOR SELECT USING (bucket_id = 'oms-storage');

-- นโยบาย Storage ให้อัปโหลดไฟล์รูปภาพได้
DROP POLICY IF EXISTS "Public Storage Insert" ON storage.objects;
CREATE POLICY "Public Storage Insert" ON storage.objects
FOR INSERT WITH CHECK (bucket_id = 'oms-storage');

-- นโยบาย Storage ให้อัปเดตหรือลบไฟล์ได้
DROP POLICY IF EXISTS "Public Storage Update" ON storage.objects;
CREATE POLICY "Public Storage Update" ON storage.objects
FOR UPDATE USING (bucket_id = 'oms-storage');

DROP POLICY IF EXISTS "Public Storage Delete" ON storage.objects;
CREATE POLICY "Public Storage Delete" ON storage.objects
FOR DELETE USING (bucket_id = 'oms-storage');
